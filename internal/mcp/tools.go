type uploadArgs struct {
	Filename  string `json:"filename" jsonschema:"Name the recipient will see on the attachment."`
	MimeType  string `json:"mime_type,omitempty" jsonschema:"Content type of the file, for example application/pdf. Defaults to application/octet-stream."`
	SizeBytes int64  `json:"size_bytes,omitempty" jsonschema:"How large the file is, if you know. It only ever narrows the ceiling this URL will accept."`
}

func (t *Tools) handleUploadURL(ctx context.Context, _ *mcp.CallToolRequest, args uploadArgs) (*mcp.CallToolResult, any, error) {
	g, err := requireGrant(ctx)
	if err != nil {
		return nil, nil, err
	}
	if t.blobs == nil {
		return toolError(fmt.Errorf("this server has no attachment storage configured, so it " +
			"cannot accept uploads. Ask the operator to check MAILROOM_ATTACHMENT_DIR")), nil, nil
	}
	if args.Filename == "" {
		return t.invalid(ctx, g, grant.Audit{Tool: "mail.upload_url"},
			fmt.Errorf("an upload needs a filename: it is the name the recipient sees")), nil, nil
	}

	upload, err := t.blobs.NewUpload(ctx, blob.UploadRequest{
		Owner:    g.OwnerID,
		GrantID:  g.ID,
		Filename: args.Filename,
		MimeType: args.MimeType,
		MaxBytes: args.SizeBytes,
	})
	if err != nil {
		return toolError(err), nil, nil
	}

	// No mailbox is touched by minting one of these, so there is no per-account read to
	// record. It is still worth a row: it is the moment a grant was given somewhere to write.
	// The filename is the client's own — it named a file it holds, not one of the operator's
	// — and it is the only thing that makes this row worth reading later, beside the send it
	// turns up in.
	if note := t.auditChange(ctx, g, grant.Audit{
		Tool: "mail.upload_url", Detail: grant.Detail{Name: args.Filename},
	}, nil); note != "" {
		return result(noted(uploadPayload(upload), note))
	}
	return result(uploadPayload(upload))
}

// uploadPayload answers with both of the deadlines an upload has, because they are different
// and a client that conflates them gets one of two wrong answers.
//
// `expires_at` is the URL's, beside the URL it describes and matching what every other
// `expires_at` in this API means: when the thing next to it stops working. It used to be the
// blob's, which is the longer of the two and is capped by nothing shorter than
// MAILROOM_ATTACHMENT_TTL — so a client on an instance configured for a day was told it had a
// day to perform a PUT the signature would refuse after ten minutes.
//
// `blob_expires_at` is the other one, and it is worth returning rather than dropping: it is
// how long the blob_id stays worth naming in a message once the bytes are up.
func uploadPayload(u blob.Upload) map[string]any {
	return map[string]any{
		"upload_url":      u.URL,
		"method":          u.Method,
		"blob_id":         u.ID,
		"filename":        u.Filename,
		"max_bytes":       u.MaxBytes,
		"expires_at":      u.URLExpires.UTC().Format(time.RFC3339),
		"blob_expires_at": u.ExpiresAt.UTC().Format(time.RFC3339),
		"how": "PUT the file's bytes to upload_url as the raw request body, with no " +
			"authorization header. The URL works once, and stops working at expires_at. Then " +
			"attach it by passing {\"blob_id\": \"" + u.ID + "\"} in the attachments list of " +
			"mail_draft or mail_send, any time before blob_expires_at.",
	}
}

// --- holding ---

// outcomeHeld is the audit outcome for a call that was recorded instead of performed. It is
// neither a success nor a refusal and the audit page treats it as its own thing: nothing was
// done, and nothing was turned away either.
const outcomeHeld = "held"

// hold records a privileged call for its owner to answer, instead of performing it, and
// answers the client with a result that says so in as many ways as a result can.
//
// It is called after the grant has authorized the call and after everything that could still
// fail on its own — the provider being reachable, the attachments resolving — so that the
// queue holds instructions that will work rather than requests that might. A caller refused
// on capability is refused, not queued.
//
// The nil check fails the call closed. A grant whose mode says hold, on a server with nowhere
// to hold anything, must not quietly perform the action instead: that is the exact shape of
// "the safe path was unavailable, so we took the unsafe one", and it is the shape this whole
// mode exists to avoid.
func (t *Tools) hold(ctx context.Context, g *grant.Grant, acct mail.Account, e grant.Audit,
	kind held.Kind, summary string, payload any) (map[string]any, error) {

	if t.holds == nil {
		return nil, fmt.Errorf(
			"this connection holds privileged actions for the owner of %s to approve, and "+
				"this server has nowhere to hold them, so nothing was done and nothing was "+
				"queued", acct.Alias)
	}

	action, err := t.holds.Hold(ctx, g, acct, e.Tool, kind, summary, payload)
	if err != nil {
		return nil, err
	}

	// The row the call would have written, with an outcome of its own. It carries everything
	// the performed call would have carried — the recipients, the subject, the ids — because
	// what the client asked for is the fact worth recording at the moment it asked, rather
	// than only when somebody gets round to answering it. A held send marked `ok` would read,
	// months later, as mail that went out.
	e.Outcome = outcomeHeld
	note := ""
	if rec := t.gate.Record(ctx, g, e); rec != nil {
		note = "this action is waiting for approval but could not be written to the audit log: " + rec.Error()
	}

	result := map[string]any{
		"held":            true,
		"action_id":       action.ID,
		"account":         acct.Alias,
		"account_address": acct.Address,
		"waiting_for":     summary,
		"approve_at":      t.holdURL,
		"note": "Nothing was done. This connection is set to hold privileged actions, so the " +
			"call above is queued for the owner of " + acct.Alias + " to approve or discard " +
			"at " + t.holdURL + ". Tell whoever you are working with that it is waiting for " +
			"approval; do not report it as done, and do not call this again to retry.",
	}
	// When it stops waiting. A client told only that something is queued will go on saying so
	// for as long as it is asked, which stops being true the moment the action expires — and
	// this is the one fact about the queue the far end cannot look up for itself.
	if ttl := t.holds.TTL(); ttl > 0 {
		result["expires_at"] = action.CreatedAt.Add(ttl).UTC().Format(time.RFC3339)
	}
	return noted(result, note), nil
}

// heldResult is the whole of a tool's answer when its call was held. The tools that group by
// mailbox use hold directly instead, because each of their mailboxes gets its own row in a
// single result.
func (t *Tools) heldResult(ctx context.Context, g *grant.Grant, acct mail.Account, e grant.Audit,
	kind held.Kind, summary string, payload any) (*mcp.CallToolResult, any, error) {

	body, err := t.hold(ctx, g, acct, e, kind, summary, payload)
	if err != nil {
		return toolError(err), nil, nil
	}
	return result(body)
}

func outcome(err error) string {
	if err != nil {
		return mail.Code(err)
	}
	return "ok"
}

// auditRead records a call whose result has not reached the caller yet, and refuses to hand
// that result over when the row cannot be written.
//
// Refusing is worth something here, which is the whole reason the two audit helpers differ:
// the mailbox has been read but nothing has been disclosed, so withholding the answer is
// what keeps "no mailbox is read unrecorded" true rather than aspirational. A read that
// failed on its own is reported as itself — there is no content to withhold, and the
// provider's error is the one that helps.
func (t *Tools) auditRead(ctx context.Context, g *grant.Grant, e grant.Audit, callErr error) error {
	e = settled(e, callErr)
	t.gate.Observe(ctx, g, e.AccountID, e.Outcome)
	rec := t.gate.Record(ctx, g, e)
	if callErr != nil || rec == nil {
		return callErr
	}
	return fmt.Errorf("this mailbox was read, and the result is being withheld because the "+
		"read could not be written to the audit log: %w", rec)
}

// auditChange records a call that has already changed a mailbox, and returns a note when the
// row could not be written.
//
// It cannot refuse, and that is not a compromise. By the time the row is written the message
// is sent and the labels are applied; the accountability is already lost, and an error would
// only report a failure that did not happen and invite a retry that does the work twice. All
// that is left is to say in the result that the change went unrecorded, rather than to
// discard the fact.
func (t *Tools) auditChange(ctx context.Context, g *grant.Grant, e grant.Audit, callErr error) string {
	e = settled(e, callErr)
	t.gate.Observe(ctx, g, e.AccountID, e.Outcome)
	if err := t.gate.Record(ctx, g, e); err != nil {
		return "this call changed the mailbox but could not be written to the audit log: " + err.Error()
	}
	return ""
}

// invalid records a call this server refused on the arguments it arrived with, and renders
// the refusal.
//
// These reach no mailbox and used to write nothing at all, so a client sending malformed
// calls all day was invisible on the one page that exists to say what a client has been
// doing. They are marked with an outcome of their own rather than folded in with the mail
// error codes, because a client with a bug and a mailbox with a problem are different things
// to go and look at.
//
// The write failure is dropped, for the reason the gate drops its own: nothing was disclosed,
// so there is no answer to withhold, and replacing the explanation the caller needs with one
// about bookkeeping helps nobody.
func (t *Tools) invalid(ctx context.Context, g *grant.Grant, e grant.Audit, err error) *mcp.CallToolResult {
	e.Outcome, e.Reason = grant.OutcomeInvalid, err.Error()
	_ = t.gate.Record(ctx, g, e)
	return toolError(err)
}

// settled fills in the half of an entry that follows from how the call ended, so no caller
// has to keep an outcome and a reason in step by hand. A reason is written only on a failure:
// it is the sentence the client was given, and a call that worked was given none.
func settled(e grant.Audit, callErr error) grant.Audit {
	e.Outcome = outcome(callErr)
	if callErr != nil {
		e.Reason = callErr.Error()
	}
	return e
}

// counted is how a tool says "this many", where zero is a measurement rather than a default.
func counted(n int) *int { return &n }

// scopedIDs renders a batch of ids for an audit entry. The store bounds the list; this only
// turns it into the strings that still identify a message after the mailbox has moved on.
func scopedIDs(ids []mail.ScopedID) []string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = id.String()
	}
	return out
}

// recipients lists the addresses a call directed mail to.
//
// Addresses only, never the display name beside one: the address is what says where mail
// actually went, and the name is whatever the caller chose to type next to it.
func recipients(in []addressArg) []string {
	out := make([]string, 0, len(in))
	for _, a := range in {
		out = append(out, a.Email)
	}
	return out
}

// noted attaches an unwritten-audit warning to a successful result, so a caller sees that
// what it asked for happened and was not recorded.
func noted(payload map[string]any, note string) map[string]any {
	if note != "" {
		payload["not_recorded"] = note
	}
	return payload
}

func asScope(err error, target **mail.ScopeError) bool { return errors.As(err, target) }
